# MAGIC # 01 · Lakehouse setup and bronze load
# MAGIC
# MAGIC Builds the **bronze** layer in Unity Catalog from the 7 raw legacy extracts, exactly as
# MAGIC `factory/bronze.py` does locally:
# MAGIC
# MAGIC * schemas `bronze`, `silver`, `gold` in the catalog (default `workspace`, the Free Edition default)
# MAGIC * a volume `bronze.raw` to hold the CSVs
# MAGIC * one Delta table per extract, typed from the legacy SQL Server DDL, **no cleaning**
# MAGIC   (messy text, NULLs and duplicate rows are kept on purpose; cleaning is the silver jobs' job)
# MAGIC * audit columns `_ingested_at` and `_source_file`
# MAGIC * `FAILFAST`: a value that doesn't fit its type stops the load instead of silently becoming NULL
# MAGIC
# MAGIC **How to run**
# MAGIC 1. Run cells 1–2 (creates schemas and the volume).
# MAGIC 2. Upload the 7 CSVs from your laptop's `data/raw/` to the volume:
# MAGIC    Catalog → `workspace` → `bronze` → Volumes → `raw` → **Upload to this volume**.
# MAGIC 3. Run the remaining cells.
# MAGIC
# MAGIC The silver and gold layers are written by the migration factory (`factory.agents.migrate`)
# MAGIC from your laptop through Databricks Connect, not by this notebook.

# COMMAND ----------

dbutils.widgets.text("catalog", "workspace", "Unity Catalog catalog")
CATALOG = dbutils.widgets.get("catalog")
RAW_PATH = f"/Volumes/{CATALOG}/bronze/raw"

for layer in ("bronze", "silver", "gold"):
    spark.sql(f"CREATE SCHEMA IF NOT EXISTS {CATALOG}.{layer}")
spark.sql(f"CREATE VOLUME IF NOT EXISTS {CATALOG}.bronze.raw")
print(f"Schemas bronze/silver/gold and volume {RAW_PATH} are ready.")

# COMMAND ----------

# Column types from data/ddl/create_tables.sql (generated by factory.bronze.bronze_ddl).
BRONZE_SCHEMAS = {
    "products": "product_code STRING, product_name STRING, line_of_business STRING, base_annual_premium DECIMAL(18,2)",
    "brokers": "broker_id STRING, broker_name STRING, county STRING, commission_rate DECIMAL(6,4), active_flag STRING",
    "customers": "customer_id STRING, first_name STRING, last_name STRING, date_of_birth DATE, county STRING, customer_since DATE, segment STRING",
    "policies": "policy_id STRING, customer_id STRING, product_code STRING, broker_id STRING, channel STRING, start_date DATE, end_date DATE, status STRING, annual_premium DECIMAL(18,2), payment_frequency STRING, sum_insured DECIMAL(18,2)",
    "premiums": "premium_id STRING, policy_id STRING, due_date DATE, paid_date DATE, amount DECIMAL(18,3)",
    "claims": "claim_id STRING, policy_id STRING, loss_date DATE, reported_date DATE, claim_type STRING, status STRING, reserve_amount DECIMAL(18,2)",
    "claim_payments": "payment_id STRING, claim_id STRING, payment_date DATE, payment_type STRING, amount DECIMAL(18,3)",
}

# Stop early, with a clear message, if any CSV hasn't been uploaded yet.
uploaded = {f.name for f in dbutils.fs.ls(RAW_PATH)}
missing = [f"{t}.csv" for t in BRONZE_SCHEMAS if f"{t}.csv" not in uploaded]
if missing:
    raise FileNotFoundError(f"Upload these to {RAW_PATH} first: {', '.join(missing)}")
print("All 7 CSVs found in", RAW_PATH)

# COMMAND ----------

import time
from pyspark.sql import functions as F

counts = {}
for table, schema in BRONZE_SCHEMAS.items():
    t0 = time.time()
    df = (spark.read.option("header", True).option("mode", "FAILFAST")
          .schema(schema).csv(f"{RAW_PATH}/{table}.csv")
          .withColumn("_ingested_at", F.current_timestamp())
          .withColumn("_source_file", F.lit(f"{table}.csv")))
    (df.write.format("delta").mode("overwrite").option("overwriteSchema", "true")
       .saveAsTable(f"{CATALOG}.bronze.{table}"))
    counts[table] = spark.table(f"{CATALOG}.bronze.{table}").count()
    print(f"bronze.{table:15s} {counts[table]:>9,} rows  {time.time() - t0:5.1f}s")

