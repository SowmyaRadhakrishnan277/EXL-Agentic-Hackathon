"""
Generate the source-to-target mapping document from a run's discovery + design output.

    python -m factory.mapping_doc runs/<run_id>     # -> docs/source_to_target_mapping.md

Everything in the document comes from the agents' JSON, so re-running after a Gemini
run (or a code change) refreshes it; nothing is hand-maintained.
"""
from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

from factory import catalog
from factory.agents.design import DesignResult, source_columns_in_order
from factory.config import ROOT
from factory.contracts.models import DiscoveryResult

OUT = ROOT / "docs" / "source_to_target_mapping.md"


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _code(text: str) -> str:
    return f"`{_cell(text)}`" if text else ""


def build(run_dir: Path) -> str:
    disc = {f.stem: DiscoveryResult.model_validate_json(f.read_text())
            for f in sorted((run_dir / "discovery").glob("J*.json"))}
    des = {f.stem: DesignResult.model_validate_json(f.read_text())
           for f in sorted((run_dir / "design").glob("J*.json"))}
    jobs = sorted(disc.values(), key=lambda r: (r.wave or 0, r.job_id))
    lang = lambda j: "SAS" if j.method.startswith("rules") else "T-SQL"
    writer = {t: j.job_id for j in jobs for t in j.output_tables}
    raw = sorted({t for j in jobs for t in j.input_tables if t.startswith("dbo.")})
    raw_cols = source_columns_in_order()

    L = [f"# Source-to-target mapping",
         "",
         f"Legacy SQL Server / SAS estate → lakehouse (bronze / silver / gold). "
         f"Generated by `python -m factory.mapping_doc {run_dir.relative_to(ROOT)}` on {date.today()} "
         f"from the discovery and design agents' output; do not edit by hand.",
         "",
         "| Layer | Holds | Naming rule |",
         "|---|---|---|",
         "| bronze | Raw source extracts, as-is, typed from the legacy DDL, plus `_ingested_at`, `_source_file` | `dbo.<t>` → `bronze.<t>` |",
         "| silver | Cleaned, conformed and intermediate tables (legacy staging) | `stg.<t>`, SAS `stg_<t>` / `<t>` → `silver.<t>` |",
         "| gold | Report-ready tables used by Finance, Actuarial, Reserving, Credit control | `rpt.<t>`, SAS `rpt_<t>` → `gold.<t>` |",
         "",
         "On Databricks each table is a Delta table `workspace.<layer>.<t>` in Unity Catalog; "
         "locally a parquet folder `lakehouse/<layer>/<t>/`.",
         "",
         "## 1. Table mapping",
         "",
         "| Legacy table | Lakehouse table | Layer | Built by | Wave | Primary key |",
         "|---|---|---|---|---|---|"]
    for t in raw:
        key = raw_cols.get(t, ["?"])[0]
        L.append(f"| `{t}` | `{catalog.lakehouse_name(t)}` | bronze | bronze loader | 0 | `{key}` |")
    for j in jobs:
        d = des.get(j.job_id)
        for t in j.output_tables:
            c = next((c for c in (d.spec.contracts if d else []) if c.table == catalog.lakehouse_name(t)), None)
            key = ", ".join(c.primary_key) if c and c.primary_key else "—"
            layer = catalog.layer_and_name(t)[0].value
            L.append(f"| `{t}` | `{catalog.lakehouse_name(t)}` | {layer} | {j.job_id[:3]} ({lang(j)}) "
                     f"| {j.wave} | `{key}` |")

    L += ["", "## 2. Job mapping", "",
          "| Wave | Job | Lang | Reads (lakehouse) | Writes (lakehouse) | Depends on |",
          "|---|---|---|---|---|---|"]
    for j in jobs:
        reads = ", ".join(f"`{catalog.lakehouse_name(t)}`" for t in j.input_tables)
        writes = ", ".join(f"`{catalog.lakehouse_name(t)}`" for t in j.output_tables)
        deps = ", ".join(x[:3] for x in j.depends_on) or "—"
        L.append(f"| {j.wave} | {j.job_id} | {lang(j)} | {reads} | {writes} | {deps} |")

    L += ["", "## 3. Column mapping", "",
          "Source columns use lakehouse names. *Legacy logic* is the expression in the legacy "
          "code (T-SQL as parsed; SAS as described by the LLM). `!` = not nullable.", ""]
    for j in jobs:
        d = des.get(j.job_id)
        for t in j.output_tables:
            target = catalog.lakehouse_name(t)
            c = next((c for c in (d.spec.contracts if d else []) if c.table == target), None)
            L += [f"### {j.job_id} → `{target}`", ""]
            if j.summary:
                L += [_cell(j.summary), ""]
            lin = {x.target_column: x for x in j.column_lineage if x.target_table == t}
            if not c or not c.columns:
                L += ["_Column lineage pending: SAS lineage needs the LLM (run discovery with "
                      "`LLM_PROVIDER=gemini`) or the job's golden output._", ""]
                continue
            L += ["| Target column | Type | Source column(s) | Legacy logic | Rule |",
                  "|---|---|---|---|---|"]
            for col in c.columns:
                x = lin.get(col.name)
                srcs = ", ".join(f"`{catalog.lakehouse_column(s)}`" for s in x.source_columns) if x else ""
                logic = _code(x.transformation) if x else "_(from golden header)_"
                null = "" if col.nullable else " !"
                key = " 🔑" if col.name in c.primary_key else ""
                L.append(f"| `{col.name}`{key} | {col.dtype}{null} | {srcs or '— (count / generated)'} "
                         f"| {logic} | {_cell(col.rule or '')} |")
            notes = [n for n in (d.notes if d else []) if "guardrail" in n] + \
                    [n for n in j.risk_notes if "guardrail" not in n]
            if notes:
                L += ["", "Risks / guardrail notes:"] + [f"- {_cell(n)}" for n in notes]
            L.append("")
    return "\n".join(L) + "\n"


def main() -> None:
    run_dir = ROOT / sys.argv[1]
    OUT.write_text(build(run_dir))
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
